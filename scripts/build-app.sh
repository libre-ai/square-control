#!/bin/sh
# Builds and signs the product bundle.
# usage: scripts/build-app.sh release|e2e [stamp]
#   release -- the configuration that ships: no E2E channel (AT-27)
#   e2e     -- test configuration: compiled with SC_E2E, never installed as the product
# The stamp (default: current UTC time) is compiled in, so two builds differ by their cdhash.
set -eu
cd "$(git rev-parse --show-toplevel)"
configuration="${1:?release|e2e}"
stamp="${2:-$(date -u +%Y%m%dT%H%M%SZ)}"
case "$configuration" in
  release) defines="" ;;
  e2e) defines="-Xswiftc -DSC_E2E" ;;
  *) echo "unknown configuration $configuration" >&2; exit 2 ;;
esac

[ -d xcframework/SCCoreFFI.xcframework ] || scripts/build-core.sh
commit="$(git rev-parse --short=12 HEAD)"
if [ -n "$(git status --porcelain)" ]; then commit="$commit-dirty"; fi
cat > shell/Sources/SquareControl/BuildInfo.swift <<EOF
// Generated by scripts/build-app.sh -- not versioned.
enum BuildInfo {
    static let stamp = "$stamp"
    static let commit = "$commit"
}
EOF

# shellcheck disable=SC2086
(cd shell && swift build -c release --product SquareControl --scratch-path ".build/$configuration" $defines \
  -Xswiftc -file-compilation-dir -Xswiftc . -Xswiftc -debug-prefix-map -Xswiftc "$(pwd)=.")
binary="$(find "shell/.build/$configuration" -path '*Release/SquareControl' -type f -perm +111 | head -1)"
[ -n "$binary" ] || { echo "SquareControl binary not found" >&2; exit 1; }

app="build/$configuration/Square Control.app"
rm -rf "$app"
mkdir -p "$app/Contents/MacOS"
cp "$binary" "$app/Contents/MacOS/SquareControl"
strip -x "$app/Contents/MacOS/SquareControl"
cat > "$app/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleIdentifier</key><string>org.libre-ai.square-control</string>
  <key>CFBundleName</key><string>Square Control</string>
  <key>CFBundleDisplayName</key><string>Square Control</string>
  <key>CFBundleExecutable</key><string>SquareControl</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>0.0.0</string>
  <key>CFBundleVersion</key><string>$stamp</string>
  <key>CFBundleDevelopmentRegion</key><string>en</string>
  <key>CFBundleLocalizations</key><array><string>en</string><string>fr</string></array>
  <key>LSMinimumSystemVersion</key><string>26.0</string>
  <key>LSUIElement</key><true/>
  <key>LSArchitecturePriority</key><array><string>arm64</string></array>
</dict></plist>
EOF
scripts/sign.sh "$app" org.libre-ai.square-control
echo "built $app stamp=$stamp commit=$commit"
